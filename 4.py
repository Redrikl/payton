def task_3():
    """
    Задача 3.
    Дан целочисленный массив и натуральный индекс (число, меньшее размера массива).
    Определить, является ли элемент по указанному индексу глобальным максимумом.
    """
    arr = list(map(int, input("Введите элементы массива через пробел: ").split()))
    idx = int(input("Введите индекс (натуральное число, < размера массива): "))
    
    if not (0 <= idx < len(arr)):
        print("Недопустимый индекс!")
        return
    
    maximum_value = max(arr)
    if arr[idx] == maximum_value:
        print("Да, элемент с этим индексом является глобальным максимумом.")
    else:
        print("Нет, элемент с этим индексом не является глобальным максимумом.")

