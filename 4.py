def task_51():
    """
    Задача 51.
    Для введённого списка построить два списка L1 и L2, где:
      - L1: неповторяющиеся элементы исходного списка (в порядке первого появления);
      - L2: сколько раз соответствующий элемент L1 встретился в исходном списке.
    Пример: исходный [5,2,6,2,3,3,5,5]
             L1 = [5,2,6,3]
             L2 = [3,2,1,2]
    """
    arr = list(map(int, input("Введите элементы массива через пробел: ").split()))
    
    L1 = []
    L2 = []
    
    for x in arr:
        if x not in L1:
            L1.append(x)
            L2.append(1)
        else:
            # Найдём индекс этого x в L1 и увеличим счётчик в L2
            idx = L1.index(x)
            L2[idx] += 1
    
    print("L1 (неповторяющиеся элементы):", L1)
    print("L2 (число вхождений соответствующих элементов):", L2)

