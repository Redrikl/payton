def arrange_russian_flag(colors: list[str]) -> list[str]:
    """
    Принимает список из трёх строк: 'белый', 'синий' и 'красный'
    в произвольном порядке.
    Возвращает новый список, упорядоченный как флаг России:
    ['белый', 'синий', 'красный'].
    """
    order = ["белый", "синий", "красный"]
    # Сортируем на основе индекса нужного цвета в списке order
    return sorted(colors, key=order.index)

def main():
    # Пример: массив (список) в случайном порядке
    flag = ["красный", "синий", "белый"]
    # Приводим к правильному порядку
    arranged_flag = arrange_russian_flag(flag)
    print(arranged_flag)  # ['белый', 'синий', 'красный']

if __name__ == "__main__":
    main()
